import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';

test('bill preview, correction, reopening and zero-cost evidence preserve the original job',async({page})=>{
  const credentials=JSON.parse(readFileSync(path.resolve(__dirname,'../../data/browser-qa/credentials.json'),'utf8'));
  await page.goto('/login');await page.getByLabel('账户',{exact:true}).fill(credentials.login_name);await page.getByLabel('密码',{exact:true}).fill(credentials.password);await page.getByRole('button',{name:'进入工作台'}).click();
  await expect(page.getByRole('heading',{name:'发现工具',exact:true})).toBeVisible();
  const get=async(route:string)=>(await (await page.request.get('/api/v1'+route)).json()).data;
  const me=await get('/auth/me');
  const post=async(route:string,body:unknown)=>{const r=await page.request.post('/api/v1'+route,{data:body,headers:{Origin:'http://127.0.0.1:13060','X-CSRF-Token':me.csrf_token,'Idempotency-Key':randomUUID()}});expect(r.ok()).toBeTruthy();return (await r.json()).data;};
  const job=async(id:string)=>{await expect.poll(async()=>(await get('/jobs/'+id)).status).toBe('succeeded');return get('/jobs/'+id);};
  const imported=await job((await post('/imports',{repository_url:'https://github.com/demo/billing-'+randomUUID().slice(0,8)})).job_id);
  const analyzed=await job((await post('/snapshots/'+imported.result_ref.snapshot_id+'/analyses',{audience:'账单核对工程验收'})).job_id);
  const id=analyzed.id;
  const initial=await get('/cost-records/'+id);const budget=await get('/cost-budget');
  await page.goto('/costs/'+id);
  const panel=page.getByRole('region',{name:'费用核对',exact:true});
  await expect(panel).toContainText('模拟账单');
  await expect(panel).toContainText('历史调用没有金额预占账本');
  const fill=async(amount:string,reason:string)=>{
    await panel.getByLabel('本作业实际净额（元）').fill(amount);
    await panel.getByLabel('账单月份').fill(budget.month);
    await panel.getByLabel('账单明细或工单定位').fill('QA明细-'+id);
    await panel.getByLabel('如何对应本作业全部调用').fill('模拟明细与本次资料分析编号匹配，仅用于隔离工程测试');
    await panel.getByLabel('本次核对、更正或撤回原因').fill(reason);
  };
  const preview=panel.getByRole('button',{name:'预览费用与预算变化'});
  await fill('-0.1','校验负数不能入账');await preview.click();
  await expect(panel.getByRole('alert')).toContainText('输入格式不正确');
  await expect(panel.getByLabel('本作业实际净额（元）')).toHaveValue('-0.1');
  await fill('0.123456','第一次模拟账单核对');await preview.click();
  const dialog=panel.getByRole('dialog',{name:'确认费用核对'});
  await expect(dialog).toContainText('¥0.123456');
  expect((await get('/cost-records/'+id)).revision).toBe(0);
  await dialog.getByRole('button',{name:'取消本次预览'}).click();expect((await get('/cost-records/'+id)).revision).toBe(0);
  await preview.click();await dialog.getByRole('button',{name:'确认保存核对'}).click();
  await expect(panel.getByRole('status')).toContainText('费用核对已保存');
  expect((await get('/cost-records/'+id)).effective.actual_micros).toBe(123456);
  await fill('0.35','更正模拟账单金额为完整净额');await preview.click();await dialog.getByRole('button',{name:'确认保存核对'}).click();
  await expect.poll(async()=>(await get('/cost-records/'+id)).revision).toBe(2);
  expect((await get('/cost-budget')).actual_micros).toBe(budget.actual_micros+350000);
  await panel.getByRole('combobox',{name:'核对结果',exact:true}).selectOption('reopened');
  await panel.getByLabel('本次核对、更正或撤回原因').fill('模拟明细归属需再次核对');await preview.click();
  await expect(dialog).toContainText('恢复待核对');
  await dialog.getByRole('button',{name:'确认保存核对'}).click();
  await expect.poll(async()=>(await get('/cost-records/'+id)).revision).toBe(3);
  expect((await get('/cost-records/'+id)).effective.held_micros).toBe(350000);
  await panel.getByRole('button',{name:'查看核对历史'}).click();
  const history=panel.getByRole('region',{name:'费用核对历史'});
  await expect(history).toContainText('核对版本 1');await expect(history).toContainText('核对版本 3');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await panel.screenshot({path:'../data/browser-qa/b03-cost-reconciliation-mobile.png'});
  await panel.getByRole('combobox',{name:'核对结果',exact:true}).selectOption('not_charged');await fill('0','模拟供应商明确确认未收费');
  await preview.click();await dialog.getByRole('button',{name:'确认保存核对'}).click();
  await expect.poll(async()=>(await get('/cost-records/'+id)).revision).toBe(4);
  const final=await get('/cost-records/'+id);expect(final.effective.actual_micros).toBe(0);expect(final.raw).toEqual(initial.raw);
  expect((await get('/cost-budget')).actual_micros).toBe(budget.actual_micros);
  await panel.getByRole('link',{name:'返回费用列表'}).click();
  await page.getByLabel('费用记录范围').selectOption('reconciled');
  await expect(page.getByRole('heading',{name:'资料分析 · '+id.slice(0,8)})).toBeVisible();
});
