import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import path from 'node:path';
const directory=path.resolve(__dirname,'../../data/browser-qa');
test('S2 discovery, candidates, confirmations and automatic version save',async({page})=>{
  const credential=JSON.parse(readFileSync(path.join(directory,'credentials.json'),'utf8'));
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/login');
  await page.getByLabel('账户',{exact:true}).fill(credential.login_name);
  await page.getByLabel('密码',{exact:true}).fill(credential.password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await page.getByLabel('主题关键词').fill('markdown');
  await page.getByRole('button',{name:'搜索 GitHub 候选'}).click();
  await page.getByRole('button',{name:'确认并评分本次候选'}).first().click({timeout:20000});
  await expect(page.getByRole('heading',{name:'本次候选中优先推荐 · 5 项'}).first()).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'导入并复核亮点'}).first().click();
  await page.getByRole('button',{name:'分析功能与亮点'}).click({timeout:20000});
  await page.getByRole('radio').check({timeout:20000});
  await page.getByRole('button',{name:'确认资料并以此工具创作'}).click();
  const studio=page.locator('.text-studio');
  await studio.getByRole('button',{name:'生成口播与文案',exact:true}).click();
  await expect(studio.locator('.history-versions summary').first()).toContainText('（2）',{timeout:20000});
  await studio.locator('.history-versions summary').first().click();
  await expect(studio.getByRole('button',{name:'采用此口播'}).first()).toBeEnabled({timeout:20000});
  await studio.getByRole('button',{name:'采用此口播'}).first().click();
  await studio.getByRole('checkbox').check();
  await studio.getByRole('button',{name:'确认口播',exact:true}).first().click();
  await studio.getByRole('button',{name:'采用此文案'}).first().click();
  await studio.getByRole('checkbox').check();
  await studio.getByRole('button',{name:'确认文案',exact:true}).first().click();
  await studio.getByRole('tab',{name:'口播',exact:true}).click();
  await studio.getByRole('button',{name:'编辑口播'}).first().click();
  await studio.getByLabel('痛点',{exact:true}).fill('已经手工改稿，想更快看清文档效果？');
  await expect(studio.getByRole('status')).toContainText('已保存为当前草稿',{timeout:10000});
  await expect(studio.getByText('当前文案基于旧稿')).toBeVisible();
  await page.reload();
  await expect(page.locator('.text-studio').getByText('已经手工改稿', {exact:false}).first()).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(directory,'s2-text-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
