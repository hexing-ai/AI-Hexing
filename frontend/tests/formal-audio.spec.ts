import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import path from 'node:path';

const directory=path.resolve(__dirname,'../../data/browser-qa');
test('voice library defaults, confirmed script to audio, immutable export, and stale audio after editing',async({page})=>{
  const credentials=JSON.parse(readFileSync(path.join(directory,'credentials.json'),'utf8'));
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1000});await page.goto('/login');
  await page.getByLabel('账户',{exact:true}).fill(credentials.login_name);await page.getByLabel('密码',{exact:true}).fill(credentials.password);
  await page.getByRole('button',{name:'进入工作台'}).click();await expect(page.getByRole('heading',{name:'发现工具',exact:true})).toBeVisible();
  const sample=Array.from(readFileSync(path.join(directory,'sample.wav')));
  const {taskId,voiceId}=await page.evaluate(async sample=>{
    const get=async(path:string)=>(await (await fetch('/api/v1'+path)).json()).data;
    if((await get('/capabilities')).mode!=='mock')throw new Error('QA must stay mock');
    const csrf=(await get('/auth/me')).csrf_token;
    const post=async(path:string,body:unknown)=>{
      const r=await fetch('/api/v1'+path,{method:'POST',headers:{'Content-Type':'application/json','X-CSRF-Token':csrf,'Idempotency-Key':crypto.randomUUID()},body:JSON.stringify(body)});
      if(!r.ok)throw new Error('Fixture API failed '+r.status);return (await r.json()).data;
    };
    const wait=async(id:string)=>{for(let i=0;i<80;i++){const j=await get('/jobs/'+id);if(j.status==='succeeded')return j;if(['failed','needs_reconciliation'].includes(j.status))throw new Error('Fixture job failed');await new Promise(r=>setTimeout(r,200));}throw new Error('Fixture job timeout');};
    const imported=await wait((await post('/imports',{repository_url:'https://github.com/demo/formal-audio-tool'})).job_id);
    const analyzed=await wait((await post(`/snapshots/${imported.result_ref.snapshot_id}/analyses`,{audience:'测试观众'})).job_id);
    const a=await get('/analyses/'+analyzed.result_ref.analysis_id);
    const review=await post(`/analyses/${a.id}/reviews`,{primary_highlight_id:a.highlights[0].id,confirmed:true});
    const task=await post('/tasks',{review_id:review.id,audience:'测试观众'});
    await wait((await post(`/tasks/${task.id}/generations`,{task_id:task.id,expected_revision:1,mode:'joint'})).job_id);
    const versions=(await get(`/tasks/${task.id}/texts`)).versions;
    for(const kind of ['script','copy']){
      const v=versions.find((v:{kind:string})=>v.kind===kind);
      for(const action of ['adopt','confirm'])await post(`/tasks/${task.id}/texts/${v.id}/${action}`,{expected_revision:(await get('/tasks/'+task.id)).revision,...(action==='confirm'?{facts_reviewed:true}:{})});
    }
    const form=new FormData();form.set('file',new Blob([new Uint8Array(sample)],{type:'audio/wav'}),'qa-sample.wav');form.set('kind','voice_sample');form.set('purpose','validation');form.set('cleanup_after',new Date(Date.now()+3600000).toISOString());form.set('consent',JSON.stringify({is_own_voice:true,purpose:'voice_clone_validation',notice_version:'S1-2026-09-08',cleanup_acknowledged:true}));
    const upload=await fetch('/api/v1/assets',{method:'POST',headers:{'X-CSRF-Token':csrf,'Idempotency-Key':crypto.randomUUID()},body:form});if(!upload.ok)throw new Error('Fixture upload failed');const asset=(await upload.json()).data;
    const enrollment=await wait((await post('/validation-runs',{kind:'voice_enrollment',contract_version:'S1-2026-09-08',sample_asset_id:asset.id,consent_record_id:asset.consent_record_id})).job_id);
    const voice=enrollment.result_ref.probe_voice_id;
    const preview=await wait((await post('/validation-runs',{kind:'voice_preview',contract_version:'S1-2026-09-08',probe_voice_id:voice,text:'正式配音之前先试听本人音色。'})).job_id);
    await post(`/probe-voices/${voice}/confirm`,{expected_revision:(await get('/probe-voices/'+voice)).revision,preview_run_id:preview.result_ref.validation_run_id,accepted:true});
    sessionStorage.setItem('hexing-selected-task',task.id);return {taskId:task.id as string,voiceId:voice as string};
  },sample);
  await page.goto('/voices');
  let card=page.getByRole('article',{name:`声音 ${voiceId.slice(0,8)}`,exact:true});
  await card.getByRole('textbox').fill('日常口播');await card.getByRole('button',{name:'保存名称',exact:true}).click();
  await expect(card.getByRole('heading',{name:'日常口播',exact:true})).toBeVisible();
  await card.getByRole('button',{name:'设为默认声音',exact:true}).click();
  await expect(card.getByRole('button',{name:'已设为默认声音',exact:true})).toBeDisabled();
  await page.reload();card=page.getByRole('article',{name:`声音 ${voiceId.slice(0,8)}`,exact:true});
  await expect(card.getByRole('heading',{name:'日常口播',exact:true})).toBeVisible();
  await expect(card.getByRole('button',{name:'已设为默认声音',exact:true})).toBeDisabled();
  await page.goto('/tasks/'+taskId);
  const studio=page.locator('.audio-studio');await expect(studio.getByRole('button',{name:'预览合成文字'})).toBeEnabled();
  await expect(studio.getByRole('combobox',{name:'用于本次配音的声音'})).toHaveValue(voiceId);
  await expect(studio.getByRole('combobox',{name:'用于本次配音的声音'})).toContainText('日常口播（默认）');
  await studio.getByLabel('工具名读法（可选）').fill('正式音频工具');
  await studio.getByLabel('替换只用于工具名发音').check();await studio.getByRole('button',{name:'预览合成文字'}).click();
  await expect(studio.getByRole('heading',{name:'即将合成的完整文字'})).toBeVisible();
  await studio.getByLabel('我已核对合成文字和工具名读法').check();await studio.getByRole('button',{name:'生成完整配音'}).click();
  await expect(studio.locator('.duration-number')).toContainText('32.00',{timeout:20000});
  await expect(studio.getByText('模拟测试音，仅验证操作流程')).toBeVisible();
  await studio.locator('audio').evaluate(async el=>{await (el as HTMLAudioElement).play();(el as HTMLAudioElement).pause();});
  await studio.getByLabel('我已检查模拟流程').check();await studio.getByRole('button',{name:'确认并采用这份配音'}).click();
  await expect(studio.getByRole('button',{name:'打包模拟验收素材'})).toBeEnabled();
  await studio.getByRole('button',{name:'打包模拟验收素材'}).click();
  await studio.locator('.package-history>summary').click();
  const download=studio.getByRole('link',{name:'下载 ZIP 素材包'});await expect(download).toBeVisible({timeout:20000});
  const event=page.waitForEvent('download');await download.click();const file=await event;
  expect(file.suggestedFilename()).toContain('模拟.zip');await file.saveAs(path.join(directory,'s3-mock-package.zip'));
  await studio.screenshot({path:path.join(directory,'s3-audio-desktop.png')});
  await page.goto('/voices');card=page.getByRole('article',{name:`声音 ${voiceId.slice(0,8)}`,exact:true});
  await card.getByRole('textbox').fill('剪辑旁白');await card.getByRole('button',{name:'保存名称',exact:true}).click();
  await expect(card.getByRole('heading',{name:'剪辑旁白',exact:true})).toBeVisible();
  await expect(card.getByRole('link',{name:'下载这段音频'})).toBeVisible();
  await page.goto('/tasks/'+taskId);await expect(page.locator('.audio-studio').getByText('已试听确认',{exact:true})).toBeVisible();
  await studio.locator('.package-history>summary').click();
  await expect(studio.getByRole('link',{name:'下载 ZIP 素材包'})).toBeVisible();
  await page.setViewportSize({width:390,height:844});await studio.screenshot({path:path.join(directory,'s3-audio-mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  const texts=page.locator('.text-studio');await texts.getByRole('button',{name:'编辑口播',exact:true}).first().click();
  await texts.getByLabel('痛点',{exact:true}).fill('准备改稿，想先检查对应版本？');
  await expect(texts.getByRole('status')).toContainText('已保存为当前草稿');
  await expect(studio.getByText('旧稿配音 · 待更新',{exact:true})).toBeVisible();
  await expect(studio.getByRole('button',{name:'打包模拟验收素材'})).toBeDisabled();
  await expect(studio.getByRole('link',{name:'下载 ZIP 素材包'})).toBeVisible();expect(errors).toEqual([]);
});
