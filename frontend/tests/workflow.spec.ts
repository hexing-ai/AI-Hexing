import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import path from 'node:path';

const directory=path.resolve(__dirname,'../../data/browser-qa');
test('S1 desktop workflow, reload recovery, writing and voice reuse',async({page})=>{
  const credential=JSON.parse(readFileSync(path.join(directory,'credentials.json'),'utf8'));
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/login');
  await page.getByLabel('账户',{exact:true}).fill(credential.login_name);
  await page.getByLabel('密码',{exact:true}).fill(credential.password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await expect(page.getByRole('heading',{name:'发现工具',exact:true})).toBeVisible();
  await page.getByLabel('GitHub 仓库地址').fill('https://github.com/demo/browser-markdown');
  await page.getByRole('button',{name:'导入仓库'}).click();
  await expect(page.getByRole('heading',{name:'demo/browser-markdown'})).toBeVisible({timeout:20000});
  await page.getByRole('button',{name:'分析功能与亮点'}).click();
  await expect(page.getByRole('radio')).toBeVisible({timeout:20000});
  await page.getByRole('radio').check();
  await page.screenshot({path:path.join(directory,'desktop-review.png'),fullPage:true});
  await page.getByRole('button',{name:'确认资料并以此工具创作'}).click();
  await expect(page.getByRole('heading',{name:'创作任务',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.locator('.task-row').first()).toBeVisible();
  await page.locator('.task-row').first().getByRole('button',{name:'写作实验'}).click();
  await expect(page.getByRole('button',{name:'生成实验稿件'})).toBeEnabled();
  await page.getByRole('button',{name:'生成实验稿件'}).click();
  await expect(page.locator('.script-block').first()).toBeVisible({timeout:20000});
  const waitForAudio=async(receipt:{job_id:string},kind:string)=>{
    const getJob=async()=>(await (await page.request.get('/api/v1/jobs/'+receipt.job_id)).json()).data;
    await expect.poll(async()=>(await getJob()).status,{timeout:20000}).toBe('succeeded');
    const job=await getJob();
    const run=(await (await page.request.get('/api/v1/validation-runs/'+job.result_ref.validation_run_id)).json()).data;
    expect(run.kind).toBe(kind);
    const src=`/api/v1/assets/${run.output.asset_id}/content`;
    await expect(page.locator(`audio[src="${src}"]`)).toBeVisible();
    expect((await page.request.get(src)).status()).toBe(200);
    return run.output.asset_id;
  };
  const submitted=()=>page.waitForResponse(r=>r.url().endsWith('/api/v1/validation-runs')&&r.request().method()==='POST');
  await page.getByLabel('样本录音',{exact:true}).setInputFiles(path.join(directory,'sample.wav'));
  const deadline=new Date(Date.now()+3600000);const local=new Date(deadline.getTime()-deadline.getTimezoneOffset()*60000).toISOString().slice(0,16);
  await page.getByLabel('本次样本清理时间').fill(local);
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'保存样本',exact:true}).click();
  await expect(page.getByText('样本已保存 ·')).toBeVisible();
  const sampleId=await page.evaluate(()=>sessionStorage.getItem('hexing-sample'));
  await page.reload();
  await expect(page.getByText('样本已保存 ·')).toBeVisible();
  expect(await page.evaluate(()=>sessionStorage.getItem('hexing-sample'))).toBe(sampleId);
  await page.getByRole('button',{name:'创建一次实验音色'}).click();
  await expect(page.getByRole('button',{name:'合成短句试听'})).toBeVisible({timeout:20000});
  const previewResponse=submitted();
  await page.getByRole('button',{name:'合成短句试听'}).click();
  const previewAsset=await waitForAudio((await (await previewResponse).json()).data,'voice_preview');
  await expect(page.getByRole('button',{name:'确认模拟流程'})).toBeEnabled({timeout:20000});
  await page.getByRole('button',{name:'确认模拟流程'}).click();
  await expect(page.getByRole('button',{name:'用另一段文字验证复用'})).toBeEnabled();
  await page.getByLabel('测试文字').fill('第二次使用同一音色，验证跨作业复用。');
  const reuseResponse=submitted();
  await page.getByRole('button',{name:'用另一段文字验证复用'}).click();
  const reuseAsset=await waitForAudio((await (await reuseResponse).json()).data,'voice_reuse');
  expect(reuseAsset).not.toBe(previewAsset);
  await page.screenshot({path:path.join(directory,'desktop-validation.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(directory,'mobile-validation.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.getByRole('link',{name:'发现工具'}).click();
  await page.screenshot({path:path.join(directory,'mobile-review.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  expect(errors).toEqual([]);
});
