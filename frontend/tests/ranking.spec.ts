import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import path from 'node:path';
const directory=path.resolve(__dirname,'../../data/browser-qa');

test('S4.1 draft, exact preview, publication, update, withdrawal and mobile management',async({page,browser})=>{
  const credentials=JSON.parse(readFileSync(path.join(directory,'credentials.json'),'utf8'));
  const fixture=JSON.parse(readFileSync(path.join(directory,'ranking-fixture.json'),'utf8'));
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(({snapshot_id,analysis_id})=>{
    sessionStorage.setItem('hexing-snapshot',snapshot_id);sessionStorage.setItem('hexing-analysis',analysis_id);
  },fixture);
  await page.goto('/login');
  await page.getByLabel('账户',{exact:true}).fill(credentials.login_name);
  await page.getByLabel('密码',{exact:true}).fill(credentials.password);
  await page.getByRole('button',{name:'进入工作台'}).click();
  await expect(page.getByRole('button',{name:'加入封神榜'})).toBeEnabled();
  await page.getByRole('button',{name:'加入封神榜'}).click();
  await expect(page.getByRole('heading',{name:'编辑公开资料'})).toBeVisible();
  const entryId=new URL(page.url()).pathname.split('/')[2];
  const anon=await browser.newContext();
  const publicList=async()=> (await (await anon.request.get('http://127.0.0.1:13060/api/v1/public/tools')).json()).data.items;
  let entry=(await (await page.request.get('/api/v1/ranking/entries/'+entryId)).json()).data;
  expect((await publicList()).some((i:{id:string})=>i.id===entry.public_id)).toBeFalsy();
  await page.getByLabel('工具名',{exact:true}).fill('工程测试：已核对的公开名称');
  await page.getByLabel('Bot 形象').selectOption('pixel');
  await expect(page.getByRole('button',{name:'预览公开内容'})).toBeDisabled();
  await page.getByRole('button',{name:'保存草稿'}).click();
  await expect(page.getByText('草稿已保存。公开内容尚未改变。',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'预览公开内容'}).click();
  const publishLabel=entry.state==='withdrawn'?'重新公开':'公开';
  await expect(page.getByRole('button',{name:publishLabel,exact:true})).toBeDisabled();
  await page.getByLabel('内容核对无误，可以公开').check();
  await page.getByRole('button',{name:publishLabel,exact:true}).click();
  await expect(page.getByText('发布成功，公开副本已更新。',{exact:true})).toBeVisible();
  expect((await publicList()).find((i:{id:string})=>i.id===entry.public_id).name).toBe('工程测试：已核对的公开名称');
  await page.getByLabel('工具名',{exact:true}).fill('工程测试：未发布修改');
  await page.getByRole('button',{name:'保存草稿'}).click();
  await expect(page.getByText('草稿已保存。公开内容尚未改变。',{exact:true})).toBeVisible();
  expect((await publicList()).find((i:{id:string})=>i.id===entry.public_id).name).toBe('工程测试：已核对的公开名称');
  await page.reload();
  await expect(page.getByLabel('工具名',{exact:true})).toHaveValue('工程测试：未发布修改');
  await page.getByRole('button',{name:'预览公开内容'}).click();
  await page.getByLabel('内容核对无误，可以公开').check();
  await page.getByRole('button',{name:'发布更新',exact:true}).click();
  await expect(page.getByText('发布成功，公开副本已更新。',{exact:true})).toBeVisible();
  expect((await publicList()).find((i:{id:string})=>i.id===entry.public_id).name).toBe('工程测试：未发布修改');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'下架此工具'}).click();
  await expect(page.getByText('已下架，草稿与历史版本保留。',{exact:true})).toBeVisible();
  expect((await publicList()).some((i:{id:string})=>i.id===entry.public_id)).toBeFalsy();
  expect((await anon.request.get('http://127.0.0.1:13060/api/v1/public/tools/'+entry.public_id)).status()).toBe(404);
  expect((await anon.request.get('http://127.0.0.1:13060/api/v1/ranking/entries/'+entryId)).status()).toBe(401);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(directory,'s4-1-management-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:path.join(directory,'s4-1-management-desktop.png'),fullPage:true});
  entry=(await (await page.request.get('/api/v1/ranking/entries/'+entryId)).json()).data;
  expect(entry.history.length).toBeGreaterThanOrEqual(3);
  expect(errors).toEqual([]);
  await anon.close();
});
